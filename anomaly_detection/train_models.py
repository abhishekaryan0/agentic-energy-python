def load_training_data_from_snowflake(well_type=None):
    """
    Load sensor data from Snowflake for training.
    Uses sensor_definitions from DB for column list when available.
    """
    logger.info(f"Loading training data from Snowflake for {well_type or 'all well types'}...")

    columns = _get_sensor_columns()
    base_cols = ['well_id', 'timestamp', 'lift_type']
    sensor_cols = [c for c in columns if c not in base_cols]

    try:
        conn = connect_snowflake()
        cursor = conn.cursor()

        sel = ', '.join(base_cols + sensor_cols)
        query = f"""
            SELECT {sel}
            FROM well_sensor_readings
            WHERE timestamp >= DATEADD(YEAR, -2, CURRENT_TIMESTAMP)
        """

        if well_type:
            query += " AND lift_type = %s"

        query += " ORDER BY well_id, timestamp"

        if well_type:
            cursor.execute(query, (well_type,))
        else:
            cursor.execute(query)
        data = cursor.fetchall()

        df = pd.DataFrame(data, columns=base_cols + sensor_cols)
        cursor.close()
        conn.close()
        
        logger.info(f"Loaded {len(df)} records from Snowflake")
        return df
        
    except Exception as e:
        logger.error(f"Failed to load data from Snowflake: {e}")
        raise

